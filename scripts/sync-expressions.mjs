/**
 * sync-expressions.mjs — sync the generator's expression defaults with the
 * CURRENT exp3 files in an assets directory.
 *
 * WHY: expression exp3 files are now hand-tuned (2026-08-27, §3 of the
 * manual) with a per-parameter Add/Overwrite blend mix that buildExpression()
 * cannot represent. Instead of keeping a stale copy in gen-motions.mjs, we
 * IMPORT the live assets so the generator's defaults ARE the current values.
 *
 * Usage: node scripts/sync-expressions.mjs <assetsDir>
 *   reads <assetsDir>/*.exp3.json (ALL of them, incl. unlinked legacy files),
 *   writes scripts/expressions-data.mjs (ES module: `export const
 *   EXPRESSIONS = {...}` with the raw JSON of each exp3).
 *
 * Safe: only reads. Never overwrites exp3 files.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const assetsDir = resolve(process.argv[2] ?? '')
if (!assetsDir) {
  console.error('用法: node scripts/sync-expressions.mjs <assetsDir>')
  process.exit(1)
}

// Collect every *.exp3.json in the assets dir (sorted, stable output).
import { readdirSync } from 'node:fs'
const files = readdirSync(assetsDir).filter((f) => f.endsWith('.exp3.json')).sort()

const expressions = {}
for (const f of files) {
  const name = f.replace(/\.exp3\.json$/, '')
  const raw = JSON.parse(readFileSync(join(assetsDir, f), 'utf8'))
  // Normalize: keep Type + Parameters verbatim (per-param Blend preserved).
  expressions[name] = { Type: raw.Type ?? 'Live2D Expression', Parameters: raw.Parameters ?? [] }
}

const outPath = new URL('./expressions-data.mjs', import.meta.url)
const body =
  `// GENERATED by scripts/sync-expressions.mjs — DO NOT EDIT BY HAND.\n` +
  `// Expression defaults are the LIVE hand-tuned exp3 files (§3 of the manual).\n` +
  `// Re-run: node scripts/sync-expressions.mjs <assetsDir>  to refresh.\n` +
  `export const EXPRESSIONS = ${JSON.stringify(expressions, null, 2)}\n`
writeFileSync(outPath, body, 'utf8')

console.log(`✓ 已同步 ${Object.keys(expressions).length} 个表情 → scripts/expressions-data.mjs`)
console.log('  表情: ' + Object.keys(expressions).join(', '))
